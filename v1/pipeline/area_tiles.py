"""Lists the 2.5 km work tiles that cover the City of Edinburgh council area and writes config/full_tiles.json.

    uv run python -m pipeline.area_tiles

The full-city pipeline processes one tile at a time so a whole-city LiDAR mosaic never has to fit in memory. A tile is listed when
it intersects any census output area of the council area, so open water far from the coast is not fetched. The output is committed;
rerun this only if the area or the tile size changes.
"""

import json
import math
import zipfile

import duckdb

from pipeline.common import RAW, ROOT, area

TILE_M = 2500
COUNCIL = "S12000036"
OUT = ROOT / "config" / "full_tiles.json"


def council_tiles(tile_m=TILE_M):
    """(easting, northing) south-west corners of the tiles that touch the council area, sorted."""
    census = RAW / "census"
    lookup = "Census_2022_Index/OA_TO_HIGHER_AREAS.csv"
    shp = f"/vsizip/{census / 'output_area_2022_boundaries_clipped_to_coast.zip'}/OutputArea2022_MHW/OutputArea2022_MHW.shp"
    with zipfile.ZipFile(census / "census_2022_index.zip") as z:
        csv = RAW / "census" / "oa_to_higher_areas.csv"
        if not csv.exists():
            csv.write_bytes(z.read(lookup))
    con = duckdb.connect()
    con.sql("INSTALL spatial; LOAD spatial;")
    west, south, east, north = area("full")["bbox_bng"]
    rows = con.execute(
        f"""
        WITH oa AS (
          SELECT o.geom FROM ST_Read('{shp}') o JOIN read_csv('{csv}') h ON o.code = h.OA2022 WHERE h.CA2019 = '{COUNCIL}'
        ), grid AS (
          SELECT e, n FROM range({math.floor(west / tile_m) * tile_m}, {math.ceil(east / tile_m) * tile_m}, {tile_m}) a(e),
                           range({math.floor(south / tile_m) * tile_m}, {math.ceil(north / tile_m) * tile_m}, {tile_m}) b(n)
        )
        SELECT e, n FROM grid WHERE EXISTS (SELECT 1 FROM oa WHERE ST_Intersects(oa.geom, ST_MakeEnvelope(e, n, e + {tile_m}, n + {tile_m})))
        ORDER BY e, n
        """
    ).fetchall()
    return [(int(e), int(n)) for e, n in rows]


def main():
    tiles = council_tiles()
    OUT.write_text(
        json.dumps(
            {
                "_comment": f"2.5 km work tiles (south-west corners, EPSG:27700) touching council area {COUNCIL}. Generated by pipeline/area_tiles.py.",
                "tile_m": TILE_M,
                "tiles": tiles,
            },
            indent=1,
        )
        + "\n"
    )
    print(f"{len(tiles)} tiles of {TILE_M} m -> {OUT}")


if __name__ == "__main__":
    main()
