"""Stage 14: match the DfT traffic counts to the road graph(s) and report how well the engine's class weights fit them.

    uv run python -m pipeline.fetch_dft_counts && uv run python -m pipeline.stage14_counts

For each road graph that exists (web/public/data/roads.json for the pilot, roads_full.json for the council area) it writes flows.json /
flows_full.json: the count points that matched an edge, with the daily flow assigned to each directed edge. It also writes
docs/traffic_counts.md, a report of coverage and of the observed flow per road class next to the engine's guessed class weights.

The flows are annual average DAILY flows from a few dozen major-road count points. They are observations, but only for the edges they
matched, and counting how busy a road is says nothing about how many vehicles it could carry.
"""

import json
from collections import Counter

import yaml

from pipeline.common import RAW, ROOT
from pipeline.counts import class_medians, match_counts, parse_popularity, select_counts, spearman

DATA = ROOT / "web" / "public" / "data"
REPORT = ROOT / "docs" / "traffic_counts.md"
GRAPHS = {"pilot": ("roads.json", "flows.json"), "full": ("roads_full.json", "flows_full.json")}
MIN_CLASSES = 5  # a rank correlation over fewer classes is noise
NOTE = "Annual average daily flow (both directions summed, shared between the directions matched). Observed at a count point, not hourly."


def inside(point, bbox):
    west, south, east, north = bbox
    return west <= point["lon"] <= east and south <= point["lat"] <= north


def build_flows(area, roads, points, config, rows):
    """flows document and the report figures for one graph."""
    in_area = [p for p in points if inside(p, roads["bbox"])]
    matches, unmatched = match_counts(in_area, roads, config["match"]["categories"], config["match"]["max_metres"])
    matched_points = {m[4] for m in matches}
    medians = class_medians(matches, roads)
    flows = {
        "estimate": False,
        "note": NOTE,
        "area": area,
        "graphEdges": len(roads["edges"]),
        "source": {
            "name": "DfT road traffic counts, City of Edinburgh",
            "url": "https://roadtraffic.dft.gov.uk/local-authorities/S12000036",
            "licence": "Open Government Licence v3.0",
            "rows": len(rows),
            "years": sorted({p["year"] for p in points}),
        },
        "matches": matches,
        "classMedians": {c: [n, m] for c, (n, m) in medians.items()},
    }
    return flows, {"inArea": in_area, "matched": matched_points, "unmatched": unmatched, "medians": medians, "matches": matches}


def section(area, roads, points, stats, weights):
    lines = [f"## {area} graph ({len(roads['edges']):,} directed edges)", ""]
    total, matched = len(points), len(stats["matched"])
    lines += [
        (
            f"- Count points in this graph's area: {len(stats['inArea'])} of {total}. Matched to an edge: **{matched}**"
            f" ({matched / max(1, len(stats['inArea'])):.0%}), covering {len(stats['matches'])} directed edges."
        ),
        "- Count points not matched, with the reason:",
    ]
    reasons = Counter(r for _, _, r in stats["unmatched"])
    lines += [f"  - {r}: {n}" for r, n in reasons.most_common()] or ["  - none"]
    lines += ["", "Observed flow per road class against the engine's guessed class weight (`POPULARITY` in `car-sim.mjs`):", ""]
    lines += ["| OSM class | count points | median daily flow per directed edge | engine weight |", "|---|---:|---:|---:|"]
    rows = [(c, n, m, weights.get(c)) for c, (n, m) in stats["medians"].items()]
    for c, n, m, w in sorted(rows, key=lambda r: -(r[3] or 0)):
        lines.append(f"| {c} | {n} | {m:,.0f} | {w if w is not None else 'default 1'} |")
    usable = [(m, w if w is not None else 1.0) for _, _, m, w in rows]
    rho = spearman([w for _, w in usable], [m for m, _ in usable]) if len(usable) >= MIN_CLASSES else None
    verdict = f"too few classes to say ({len(usable)}; at least {MIN_CLASSES} needed)" if rho is None else f"{rho:+.2f}"
    lines += ["", f"Rank correlation of class weight and median observed flow across these classes: {verdict}.", ""]
    return lines


def main():
    config = yaml.safe_load((ROOT / "config" / "flows.yaml").read_text())
    source = RAW / "counts" / "dft_aadf_edinburgh.json"
    if not source.exists():
        raise SystemExit(f"{source} not found. Run: uv run python -m pipeline.fetch_dft_counts")
    rows = json.loads(source.read_text())
    points = select_counts(rows, config["dft"])
    weights = parse_popularity((ROOT / "web" / "src" / "engine" / "car-sim.mjs").read_text())
    by_category = Counter(p["category"] for p in points)
    report = [
        "# Traffic counts matched to the road graph",
        "",
        "Generated by `pipeline/stage14_counts.py` (`make counts`). Observed counts, matched by position and road class; the flows are",
        "annual average **daily** figures for both directions, taken at a few dozen major-road count points. They say how busy those",
        "roads are, not how many vehicles a road can carry, and say nothing about the side streets.",
        "",
        (
            f"Source: DfT road traffic statistics, City of Edinburgh, {len(rows)} rows. Used: the latest Counted year per count point"
            f" from {config['dft']['first_year']}, skipping {', '.join(map(str, config['dft']['excluded_years']))}."
            f" That leaves **{len(points)} count points** ({', '.join(f'{k} {v}' for k, v in sorted(by_category.items()))}),"
            f" counted in {min(p['year'] for p in points)} to {max(p['year'] for p in points)}."
        ),
        "",
    ]
    for area, (roads_file, flows_file) in GRAPHS.items():
        path = DATA / roads_file
        if not path.exists():
            print(f"{area}: {path.name} not built yet, skipped")
            continue
        roads = json.loads(path.read_text())
        flows, stats = build_flows(area, roads, points, config, rows)
        (DATA / flows_file).write_text(json.dumps(flows, separators=(",", ":")))
        report += section(area, roads, points, stats, weights)
        print(
            f"{area}: {len(stats['matched'])} of {len(stats['inArea'])} count points matched, {len(flows['matches'])} edges -> {flows_file}"
        )
    REPORT.write_text("\n".join(report) + "\n")
    print(f"report -> {REPORT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
